/* what a brochure's two rates give on Balsam's own applicants: 2,000 CVs a year, 100 suitable */
export function brochureImplied(v, total = 2000, suitable = 100) {
  const found = Math.round(suitable * v.found / 100);
  const missed = suitable - found;
  const unsuitable = total - suitable;
  const wronglyPassed = Math.round(unsuitable * (100 - v.cleared) / 100);
  const shortlist = found + wronglyPassed;
  return { total, suitable, found, missed, wronglyPassed, shortlist,
    shareSuitable: found / shortlist, accuracy: (found + unsuitable - wronglyPassed) / total, rejectAllAccuracy: unsuitable / total };
}

